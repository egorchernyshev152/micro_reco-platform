export type TranslationKey = Exclude<keyof typeof translations.ru, never>;

export const useTranslation = () => {
  const language = usePreferencesStore((state) => state.language);
  return useMemo(() => {
    const dict = translations[language];
    return {
      t: (key: TranslationKey) => dict[key] as string,
      dict,
      language
    };
  }, [language]);
};

export const formatProfileStats = (language: AppLanguage, watched: number, fav: number, wl: number, favActors = 0) => {
  if (language === 'en') {
    return `${watched} watched • ${fav} favorite movies • ${wl} in watchlist • ${favActors} favorite actors`;
  }
  return `${watched} фильмов просмотрено • ${fav} любимых фильмов • ${wl} ждут своего часа • ${favActors} любимых актёров`;
};

export const formatFollowStats = (language: AppLanguage, followers: number, following: number) => {
  if (language === 'en') {
    return `${followers} followers • ${following} following`;
  }
  return `${followers} подписчиков • ${following} подписок`;
};
